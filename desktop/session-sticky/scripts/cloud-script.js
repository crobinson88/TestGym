"use strict";

// Builds cloud/setup-script.sh: the text pasted into a Claude Code cloud
// environment's Setup script box. It writes the hook + installer into
// ~/.claude and wires the hook in, so every session in that environment
// reports to the sticky note. Generated from hook/ so the two can't drift
// (test/sources.js checks the committed copy).
//
//   npm run cloud-script

const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "cloud", "setup-script.sh");

function heredoc(target, body, tag) {
  if (body.includes(tag)) throw new Error(`${target} contains its heredoc terminator`);
  return `cat > "${target}" <<'${tag}'\n${body.replace(/\n?$/, "\n")}${tag}\n`;
}

function buildCloudScript(hookSrc, installSrc) {
  return [
    "#!/bin/bash",
    "# Session Sticky: report every Claude Code session in this cloud environment",
    "# to the sticky note on your desktop. Generated by `npm run cloud-script` in",
    "# desktop/session-sticky — don't edit by hand.",
    "#",
    "# Also needs, in this environment's settings:",
    "#   Environment variable  WORKSTREAM_TOKEN=<from your cloud-setup.txt>",
    "#   Network access        allow rgslyxzeyjiypzilpxpf.supabase.co",
    "# Never fails the environment: every step is best-effort.",
    "",
    'mkdir -p "$HOME/.claude"',
    heredoc("$HOME/.claude/workstream-hook.mjs", hookSrc, "WORKSTREAM_HOOK_EOF"),
    heredoc("$HOME/.claude/workstream-install-hook.mjs", installSrc, "WORKSTREAM_INSTALL_EOF"),
    'node "$HOME/.claude/workstream-install-hook.mjs" "$HOME/.claude/workstream-hook.mjs" || true',
    "",
  ].join("\n");
}

function readSources() {
  return {
    hookSrc: fs.readFileSync(path.join(ROOT, "hook", "workstream-hook.mjs"), "utf8"),
    installSrc: fs.readFileSync(path.join(ROOT, "hook", "install-hook.mjs"), "utf8"),
  };
}

function currentCloudScript() {
  const { hookSrc, installSrc } = readSources();
  return buildCloudScript(hookSrc, installSrc);
}

if (require.main === module) {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, currentCloudScript());
  console.log(`cloud setup script → ${path.relative(process.cwd(), OUT)}`);
}

module.exports = { buildCloudScript, currentCloudScript, OUT };
